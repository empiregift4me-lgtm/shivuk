function loadAffirmationState() {
  try {
    return JSON.parse(localStorage.getItem(STORE_KEYS.affirmationState)) || null;
  } catch (e) {
    return null;
  }
}

function saveAffirmationState(state) {
  localStorage.setItem(STORE_KEYS.affirmationState, JSON.stringify(state));
}

function renderAffirmationHeadline(sentence) {
  const line = document.getElementById("daily-affirmation-line");
  if (!line) return;
  line.textContent = sentence;
  line.classList.add("is-visible");
}

function showAffirmationSplash(sentence) {
  const overlay = el("div", { class: "affirmation-overlay" });
  const particles = Array.from({ length: 12 }).map((_, i) => el("span", { class: `affirmation-particle p${i}` }));
  const closeBtn = el("button", { type: "button", class: "affirmation-close", title: "סגירה", text: "✕" });
  const card = el("div", { class: "affirmation-card" }, [
    el("div", { class: "affirmation-glow" }),
    ...particles,
    closeBtn,
    el("p", { class: "affirmation-text", text: sentence })
  ]);
  overlay.appendChild(card);
  document.body.appendChild(overlay);

  let dismissed = false;
  function dismiss() {
    if (dismissed || !closeBtn.classList.contains("is-ready")) return;
    dismissed = true;
    overlay.classList.remove("is-visible");
    setTimeout(() => overlay.remove(), 400);
  }

  closeBtn.addEventListener("click", dismiss);
  requestAnimationFrame(() => overlay.classList.add("is-visible"));
  // כפתור הסגירה נשאר חסום כדי שהמשפט באמת ייקלט, לפני שאפשר לסגור אותו
  setTimeout(() => closeBtn.classList.add("is-ready"), DAILY_AFFIRMATION_CLOSE_DELAY_MS);
}

// נקראת מיד אחרי הזנת סיסמה מוצלחת - בוחרת (או שומרת) את משפט היום, ומציגה את החלונית רק אם עברו 24 שעות מהפעם האחרונה
function initDailyAffirmation() {
  const now = Date.now();
  let state = loadAffirmationState();
  const dueForNewSplash = !state || now - state.lastShownAt >= DAILY_AFFIRMATION_INTERVAL_MS;

  if (dueForNewSplash) {
    const sentence = DAILY_AFFIRMATIONS[Math.floor(Math.random() * DAILY_AFFIRMATIONS.length)];
    state = { sentence, lastShownAt: now };
    saveAffirmationState(state);
  }

  renderAffirmationHeadline(state.sentence);
  if (dueForNewSplash) showAffirmationSplash(state.sentence);
}
